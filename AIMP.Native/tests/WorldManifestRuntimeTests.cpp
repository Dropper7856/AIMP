#include "aimp/WorldEntityRegistry.h"
#include "aimp/SignatureResolver.h"
#include "aimp/LevelGenerationTracker.h"
#include "aimp/Diagnostics.h"
#include "aimp/ReplicationCore.h"
#include "aimp/GameThreadDispatcher.h"
#include "aimp/WorldInteractionAdapters.h"
#include <array>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <thread>
#include <chrono>

namespace aimp {
struct WorldManifestRuntimeTestAccess {
    static void EnableFileOnlyPreparation(WorldEntityRegistry& registry) noexcept {
        // Initialize normally certifies game addresses. File/index parsing
        // never dereferences them; this test needs no running game.
        registry.initialized_ = true;
    }
};
}

// Exercises the production native reader and activation path using a manifest
// generated by the managed compiler. No game image or native callbacks run.
int wmain() {
    wchar_t source[32768]{};
    if (GetEnvironmentVariableW(L"AIMP_TEST_WORLD_MANIFEST", source, 32768) == 0U) {
        std::cout << "SKIP: AIMP_TEST_WORLD_MANIFEST is not configured\n";
        return 77;
    }
    aimp::BuildProfile profile{};
    aimp::SignatureResolver resolver(nullptr, 0U, profile, false);
    aimp::LevelGenerationTracker generations;
    const auto generation = static_cast<std::uint32_t>(generations.BeginTransition().generation);
    aimp::Diagnostics diagnostics;
    aimp::WorldEntityRegistry registry(resolver, generations, diagnostics);
    aimp::WorldManifestRuntimeTestAccess::EnableFileOnlyPreparation(registry);
    const auto load = [&](const std::filesystem::path& path, std::string& error) {
        const auto deadline = GetTickCount64() + 60000U;
        do {
            if (registry.LoadManifestRuntimeIndex(path, generation, error)) return true;
            if (error != "WORLD_MANIFEST_PREPARING") return false;
            std::this_thread::sleep_for(std::chrono::milliseconds(10));
        } while (GetTickCount64() < deadline);
        error = "native manifest preparation timed out";
        return false;
    };
    std::string error;
    if (!load(source, error) || !registry.RuntimeCaptureReady()) {
        std::cerr << "FAIL managed manifest -> native registry: " << error << '\n';
        return 1;
    }

    // Exercise the production reservation/publication queue, not a model of
    // it: one open causal turn produces 5000 ROOTs while a consumer drains any
    // fully published segments. The old end-only publication exhausted 256
    // reservations and failed this scenario before the turn could end.
    aimp::GameThreadDispatcher dispatcher;
    if (!aimp::replication_core::Initialize(generations, dispatcher, registry, error)) return 1;
    aimp::replication_core::BeginCausalTurn();
    std::uint64_t consumed = 0U;
    const auto consume = [&]() {
        aimp::WorldIntent intent{};
        while (aimp::replication_core::TryPopOutboundIntent(intent)) {
            aimp::world_interactions::CompositePublicInputEvent root{};
            if (!aimp::world_interactions::DecodeCompositePublicInputPayload(
                    std::span<const std::byte>(intent.payload.bytes.data(), intent.payload.size), root) ||
                root.observationId != consumed + 1U || intent.clientSequence != consumed + 1U ||
                root.rootOrdinal != consumed % 32U || root.rootCount != (consumed < 4992U ? 32U : 8U)) return false;
            ++consumed;
        }
        return true;
    };
    for (std::uint64_t i = 1U; i <= 5000U; ++i) {
        aimp::world_interactions::CompositePublicInputEvent root{};
        root.observationId = i; root.publicInputShortGuid = 1U; root.retailRoot = true;
        root.causalSerial = 1U; root.segmentSerial = 1U; root.targetEntity = {1U, 1U};
        root.contextKind = aimp::world_interactions::PublicContextKind::Autonomous;
        aimp::WorldPayload payload{};
        if (!aimp::world_interactions::EncodeCompositePublicInputPayload(root, payload) ||
            !aimp::replication_core::SubmitLocalIntent({1U, 1U}, aimp::WorldMutationKind::Event,
                aimp::world_interactions::kOperationCompositePublicInput,
                std::span<const std::byte>(payload.bytes.data(), payload.size)) || !consume()) {
            std::cerr << "FAIL burst publication at ROOT " << i << '\n';
            return 1;
        }
    }
    if (consumed != 4992U) return 1; // the short tail is still unsealed
    aimp::replication_core::EndCausalTurn();
    if (!consume() || consumed != 5000U ||
        aimp::replication_core::DiagnosticsSnapshot().causalRecoveryRequired) return 1;
    aimp::replication_core::BeginLogicalShutdown();

    // A stale compiler header must still be rejected. Do not loosen version
    // validation to solve a missing constant update.
    wchar_t directory[MAX_PATH]{}, temporary[MAX_PATH]{};
    if (GetTempPathW(MAX_PATH, directory) == 0U ||
        GetTempFileNameW(directory, L"wmv", 0U, temporary) == 0U) return 1;
    struct RemoveTemporary {
        const wchar_t* path;
        ~RemoveTemporary() { DeleteFileW(path); }
    } cleanup{temporary};
    std::array<char, 48U> header{};
    std::ifstream input(std::filesystem::path(source), std::ios::binary);
    if (!input.read(header.data(), static_cast<std::streamsize>(header.size()))) return 1;
    header[12] ^= 1; // compiler version is little-endian at offset 12
    {
        std::ofstream output(std::filesystem::path(temporary), std::ios::binary | std::ios::trunc);
        output.write(header.data(), static_cast<std::streamsize>(header.size()));
    }
    if (load(temporary, error) || error.find("header is incompatible") == std::string::npos) {
        std::cerr << "FAIL stale compiler header was not rejected: " << error << '\n';
        return 1;
    }
    std::cout << "PASS: native manifest load/rejection; 5000-ROOT production publication without loss or fail-stop\n";
    return 0;
}
