#pragma once

#include "aimp/Common.h"

#include <cstddef>
#include <cstdint>
#include <string>

namespace aimp {

class HookManager;
class LevelGenerationTracker;

namespace world_sync {

struct DoorEvent final {
    std::uint32_t levelGeneration{};
    std::uint64_t sequence{};
    std::uint32_t entityA{};
    std::uint32_t entityB{};
    std::uint32_t signal{};
    std::uint64_t valueBits{};
};

struct DoorInjectionResult final {
    std::uint64_t sequence{};
    std::uint32_t entityA{};
    std::uint32_t entityB{};
    std::uint32_t signal{};
    bool injected{};
};

struct DoorRuntimeDiagnostics final {
    std::uint64_t version{};
    std::uint64_t doorNativeDispatches{};
    std::uint64_t lockSwitchNativeDispatches{};
    std::uint64_t resolvedTrackedDispatches{};
    std::uint64_t observedEvents{};
    std::uint64_t replayAttempts{};
    std::uint64_t replaySuccesses{};
    std::uint64_t replayMissingRuntime{};
    std::uint64_t replayMissingContext{};
    std::uint64_t replaySyntheticContextAttempts{};
    std::uint64_t replayInvalidNativeObject{};
    std::uint64_t replayDeferredRetries{};
    std::uint64_t replayRetryExhausted{};
    std::uint64_t suppressedRemoteEchoes{};
};

[[nodiscard]] constexpr ModuleReport Report() noexcept {
    return {
        "WorldSync",
        ModuleStatus::PartiallyImplemented,
        "Door_Package v11.8 keeps targeted retail Door/LogicSwitch hooks and adds bounded backoff replay plus long-lived remote-output suppression so a delayed CATHODE transition cannot echo back over the network or hammer the engine every frame."};
}

bool Install(
    std::uintptr_t moduleBase,
    std::size_t moduleSize,
    HookManager& hooks,
    LevelGenerationTracker& generations,
    std::string& error);

[[nodiscard]] bool Installed() noexcept;
[[nodiscard]] DoorRuntimeDiagnostics DiagnosticsSnapshot() noexcept;

// Called from the launcher IPC worker. The actual CATHODE invocation remains
// on the engine thread and is performed by PumpOnEngineThread.
bool QueueRemoteDoorEvent(const DoorEvent& event) noexcept;

// Called by LauncherIPC to drain bounded observations generated by targeted
// Door/LogicSwitch detours. No file I/O or network I/O occurs in a detour.
bool TryPopObservedDoorEvent(DoorEvent& event) noexcept;

// Completed replay results are drained by LauncherIPC on its worker thread so
// diagnostics never perform file I/O inside a Door/LogicSwitch or engine hook.
bool TryPopInjectionResult(DoorInjectionResult& result) noexcept;

// Called from the already validated engine-thread observation hooks.
void PumpOnEngineThread() noexcept;

void BeginLogicalShutdown() noexcept;

} // namespace world_sync
} // namespace aimp
